#pragma once
#include <Arduino.h>

// Состояния лица Ясмины.
enum FaceState : uint8_t {
  FACE_IDLE = 0,   // тынычлык — ждём, дышим, моргаем
  FACE_LISTEN,     // тыңлыйм — слушаю, глаза шире и ярче
  FACE_SPEAK,      // сөйлим — нейтральное говорящее лицо
  FACE_HAPPY,      // шат — радость, глаза полумесяцами
  FACE_LOVE,       // гашыйк — влюблённость: сердечки вместо глаз, розовый
  FACE_WINK,       // шаян — озорство: подмигивает, рядом искорки
  FACE_SURPRISE,   // гаҗәп — удивление: круглые глаза, брови вверх
  FACE_SLEEP,      // йокы — сон: глаза закрыты, месяц, холодный синий
  FACE_SAD,        // моң — грусть: брови домиком, слезинка
  FACE_STATE_COUNT
};

namespace face {

void begin();

// Переключить состояние. instant = true — без плавного морфа.
void setState(FaceState s, bool instant = false);
FaceState state();

// Говорение — отдельная ось, не эмоция: Ясмина может говорить с любым
// выражением лица. Рот смешивается между сомкнутым и раскрытым контурами
// текущего состояния, остальное лицо при этом живёт своей жизнью.
//
//     face::setState(FACE_HAPPY);   // радуется
//     face::setSpeaking(true);      // и при этом говорит
//
// Состояние FACE_SPEAK включает говорение само — это просто нейтральное
// говорящее лицо, такая же эмоция, как остальные.
void setSpeaking(bool on);
bool isSpeaking();

// Размышление — тоже отдельная ось, поверх любой эмоции: Ясмина не меняет
// выражения, но взгляд уходит вверх и медленно плывёт по дуге, как у человека,
// который вспоминает. Включается на время, пока ждём ответ сервера.
void setThinking(bool on);
bool isThinking();

// Уровень речи 0..1 — если подавать сюда громкость TTS, рот пойдёт по звуку.
// Не вызывать (или передать -1) — рот будет шевелиться сам.
void setSpeechLevel(float level);

// Один кадр: досчитать анимацию и вылить её на экран.
// Зовётся из loop() как можно чаще, сама себя ограничивает по FPS.
void tick();

const char *stateName(FaceState s);

// Реальная частота кадров за последнюю секунду — чтобы видеть, во что упёрлись.
float fps();

// Цвет незанятой части экрана: им заливается фон один раз при старте.
uint16_t backgroundColor();

// Сколько микросекунд уходит на стадии кадра — чтобы видеть, во что упёрлись.
struct Profile { uint32_t rasterUs, glowUs, compUs, pushUs; };
Profile profile();

} // namespace face
