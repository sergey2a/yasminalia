#pragma once
#include "face.h"

// ---------------------------------------------------------------------------
// Черты лица Ясмины — замкнутые контуры из кубических кривых Безье.
//
// Каждый контур состоит ровно из PATH_SEGS сегментов и хранится как тройки
// «контрольная, контрольная, узловая». Начальная точка контура — узловая точка
// последнего сегмента, то есть контур всегда замкнут.
//
// ВАЖНО: у одной и той же черты во всех состояниях должно быть одинаковое
// число точек в одинаковом порядке — тогда переход между состояниями это
// простая интерполяция координат. Если добавляешь точку в одном состоянии,
// добавь её во всех.
//
// Координаты локальные, в пикселях панели: X вправо, Y вниз, начало — якорь
// черты. Якорь глаза, брови и украшения задаёт правую половину лица, левая
// зеркалится. Якорь с x = 0 ставит черту по центру: обе копии совпадут.
//
// Экран цветной, и цвет тоже принадлежит состоянию: ink, decorInk и glowInk
// интерполируются при переходе наравне с координатами, поэтому переход из
// тёплого idle в розовый love — плавная заливка, а не подмена палитры.
//
// Узлы контура (в этом порядке):
//   n0 — левый край        n3 — правый нижний угол
//   n1 — вершина           n4 — середина нижней кромки
//   n2 — правый край       n5 — левый нижний угол
// У глаза n4 лежит ВЫШЕ n3 и n5 — получается прищур-полумесяц;
// если опустить n4 ниже — тот же контур становится открытым глазом.
// ---------------------------------------------------------------------------

namespace face {

constexpr int PATH_SEGS = 6;
constexpr int PATH_PTS  = PATH_SEGS * 3;

struct Pt   { float x, y; };
struct Path { Pt p[PATH_PTS]; };
struct Rgb  { float r, g, b; };   // 0..255, интерполируется вместе с формами

// Один облик: якоря, контуры и параметры поведения.
//
// Ртов два: сомкнутый и раскрытый, и оба свои у каждой эмоции. Речь — это
// не отдельное состояние лица, а отдельная ось: Ясмина может говорить с любым
// выражением, и рот при этом смешивается между mouth и mouthTalk по громкости.
struct Look {
  Pt    eyeAt;    Path eye;
  Pt    browAt;   Path brow;
  Pt    mouthAt;  Path mouth;      // сомкнутый
                  Path mouthTalk;  // раскрытый, тот же якорь
  Pt    decorAt;  Path decor;      // украшение: сердечко, месяц, слезинка, искра
  float decorOn;    // видимость украшения 0..1
  float decorMirror;// 1 — рисовать парой зеркально, 0 — одной фигурой по центру
  float wink;       // 0 — глаза одинаковы, 1 — правый прикрыт (подмигивание)
  Rgb   ink;        // цвет глаз, бровей и рта
  Rgb   decorInk;   // цвет украшения
  Rgb   glowInk;    // цвет ореола
  float glow;       // множитель яркости ореола
  float gazeAmp;    // насколько гуляет взгляд, px
  float blinkEvery; // средний интервал моргания, сек
};

extern const Look LOOK[FACE_STATE_COUNT];

} // namespace face
